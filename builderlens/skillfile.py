"""Turn the report's agent guidance into files coding agents load: a Claude Code skill and an
AGENTS.md section for Codex. Every instruction keeps the measured facts it was derived from."""
import os
import shutil

SKILL_NAME = "builder-lens-working-style"
SKILL_HOME = os.path.expanduser(f"~/.claude/skills/{SKILL_NAME}")


def _block(title, items):
    if not items:
        return ""
    lines = [f"## {title}", ""]
    for i, x in enumerate(items, 1):
        lines.append(f"{i}. {x['text']}")
        lines.append(f"   Based on: {' '.join(x['why'])}")
    return "\n".join(lines) + "\n"


def body(skill, header):
    h = header
    intro = (f"Generated by Builder Lens on {h['date']} from {h['sessions']} of this developer's own sessions "
             f"({h['scope']}). Each instruction lists the measured facts it's based on. Re-run "
             "`python3 builder_lens.py` to refresh it.")
    blocks = [_block("Do", skill["rules"]), _block("Avoid", skill["avoid"]),
              _block("How they communicate", skill["communication"])]
    return "\n\n".join(["# Working with this developer", intro] + [b.rstrip() for b in blocks if b]) + "\n"


def skill_md(skill, header):
    desc = ("How this developer works with coding agents, learned from their own sessions by Builder Lens: "
            "when to plan, how to verify, how they steer and approve. Use at the start of any coding task "
            "in their repos.")
    return f"---\nname: {SKILL_NAME}\ndescription: {desc}\n---\n\n{body(skill, header)}"


def agents_md(skill, header):
    return ("<!-- builder-lens:start (generated; re-run builder_lens.py to refresh) -->\n"
            f"{body(skill, header)}<!-- builder-lens:end -->\n")


def write(skill, header, out_dir):
    """Write out/skill/<name>/SKILL.md and out/skill/AGENTS.md; return their paths."""
    sdir = os.path.join(out_dir, "skill", SKILL_NAME)
    os.makedirs(sdir, exist_ok=True)
    paths = {"skill": os.path.join(sdir, "SKILL.md"), "agents": os.path.join(out_dir, "skill", "AGENTS.md")}
    with open(paths["skill"], "w", encoding="utf-8") as fh:
        fh.write(skill_md(skill, header))
    with open(paths["agents"], "w", encoding="utf-8") as fh:
        fh.write(agents_md(skill, header))
    return paths


def install(skill_path):
    """Copy SKILL.md into ~/.claude/skills/<name>/, replacing only Builder Lens's own skill."""
    os.makedirs(SKILL_HOME, exist_ok=True)
    dest = os.path.join(SKILL_HOME, "SKILL.md")
    shutil.copyfile(skill_path, dest)
    return dest
